[CmdletBinding()]
param(
  [ValidateSet('auto', 'task', 'startup', 'runkey')][string]$Method = 'auto',
  [string]$ConfigPath = '',
  [string]$TaskName = 'DSH-LAN-Relay-Hub',
  [switch]$Remove,
  [switch]$NoStart,
  [switch]$Force
)

$ErrorActionPreference = 'Stop'
$ProjectDir = Split-Path -Parent $PSScriptRoot

if (-not $ConfigPath) {
  $ConfigPath = Join-Path $env:USERPROFILE '.dsh\lan-relay\config.json'
}

$startupDir = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup'
$startupShortcut = Join-Path $startupDir 'DSH LAN Relay.lnk'
$legacyStartupVbs = Join-Path $startupDir 'DSH-LAN-Relay.vbs'
$runKeyPath = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'
$runKeyName = 'DSH-LAN-Relay'
$launcherVbs = Join-Path (Split-Path -Parent $ConfigPath) 'launch-hub.vbs'

function Get-LauncherCommand {
  return "wscript.exe `"$launcherVbs`""
}

function New-Launcher {
  param([string]$NodePath, [string]$HubPath, [string]$LogPath)
  $vbs = @"
' DSH LAN Relay Hub hidden launcher with auto-restart - generated by dsh-lan-relay
' Delete the autostart entry (and this file) to disable.
Set sh = CreateObject("WScript.Shell")
cmd = """$NodePath"" ""$HubPath"" --config ""$ConfigPath"" --log ""$LogPath"""
failures = 0
Do
  started = Timer
  code = sh.Run(cmd, 0, True)
  elapsed = Timer - started
  If elapsed < 0 Then elapsed = elapsed + 86400
  If elapsed > 30 Then failures = 0
  If code = 2 Then WScript.Quit 0
  If code <> 0 Then
    failures = failures + 1
    If failures >= 3 Then WScript.Quit code
  Else
    failures = 0
  End If
  WScript.Sleep 3000
Loop
"@
  try {
    [System.IO.File]::WriteAllText($launcherVbs, $vbs, (New-Object System.Text.ASCIIEncoding))
  } catch {
    Set-Content -Path $launcherVbs -Value $vbs -Encoding Ascii
  }
}

function Remove-All {
  $removed = @()

  $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if ($task) {
    try { Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue } catch { }
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
    $removed += "计划任务 $TaskName"
  }

  if (Test-Path $startupShortcut) {
    Remove-Item $startupShortcut -Force
    $removed += "启动文件夹快捷方式 $startupShortcut"
  }

  if (Test-Path $legacyStartupVbs) {
    Remove-Item $legacyStartupVbs -Force
    $removed += "旧启动项 $legacyStartupVbs"
  }

  try {
    $value = Get-ItemProperty -Path $runKeyPath -Name $runKeyName -ErrorAction SilentlyContinue
    if ($value) {
      Remove-ItemProperty -Path $runKeyPath -Name $runKeyName -Force
      $removed += "注册表自启项 HKCU\...\Run\$runKeyName"
    }
  } catch { }

  try {
    Get-CimInstance Win32_Process -Filter "Name='wscript.exe'" |
      Where-Object { $_.CommandLine -like '*launch-hub.vbs*' } |
      ForEach-Object {
        Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
        $removed += "启动器进程 PID $($_.ProcessId)"
      }
  } catch { }

  if ($removed.Count) {
    Write-Host "已移除：$($removed -join '；')" -ForegroundColor Green
  } else {
    Write-Host '没有找到任何自启项。' -ForegroundColor Yellow
  }
  Write-Host "hub 本身如果还在运行，需要的话手动结束：Get-NetTCPConnection -LocalPort 8787 -State Listen" -ForegroundColor DarkGray
}

if ($Remove) {
  Remove-All
  exit 0
}

if (-not (Test-Path $ConfigPath)) {
  Write-Host "配置文件不存在：$ConfigPath" -ForegroundColor Red
  Write-Host '请先运行：scripts\setup.ps1 -Role hub' -ForegroundColor Yellow
  exit 1
}

try {
  $nodePath = (Get-Command node -ErrorAction Stop).Source
} catch {
  Write-Host '未找到 node.exe，请安装 Node.js 18+ 并加入 PATH 后重试。' -ForegroundColor Red
  exit 1
}

$hubPath = Join-Path $ProjectDir 'hub.mjs'
if (-not (Test-Path $hubPath)) {
  Write-Host "找不到 hub.mjs：$hubPath" -ForegroundColor Red
  exit 1
}

$hubData = Join-Path (Split-Path -Parent $ConfigPath) 'hub'
if (-not (Test-Path $hubData)) { New-Item -ItemType Directory -Force -Path $hubData | Out-Null }
$logPath = Join-Path $hubData 'hub.log'

New-Launcher -NodePath $nodePath -HubPath $hubPath -LogPath $logPath

# 老版本可能残留启动文件夹 VBS，统一清掉，避免重复启动
if (Test-Path $legacyStartupVbs) { Remove-Item $legacyStartupVbs -Force }

function Install-Task {
  $argument = "`"$hubPath`" --config `"$ConfigPath`" --log `"$logPath`""
  $action = New-ScheduledTaskAction -Execute $nodePath -Argument $argument -WorkingDirectory $ProjectDir
  $trigger = New-ScheduledTaskTrigger -AtLogOn
  $settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -RestartCount 3 `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -MultipleInstances IgnoreNew `
    -ExecutionTimeLimit ([TimeSpan]::Zero)
  $description = 'DSH LAN Relay Hub 开机自启（dsh-lan-relay 生成）。删除：scripts\install-autostart.ps1 -Remove'
  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Description $description -Force -ErrorAction Stop | Out-Null
}

function Install-StartupShortcut {
  if (-not (Test-Path $startupDir)) { New-Item -ItemType Directory -Force -Path $startupDir | Out-Null }
  $shell = New-Object -ComObject WScript.Shell
  $shortcut = $shell.CreateShortcut($startupShortcut)
  $shortcut.TargetPath = 'C:\Windows\System32\wscript.exe'
  $shortcut.Arguments = "`"$launcherVbs`""
  $shortcut.WorkingDirectory = $ProjectDir
  $shortcut.WindowStyle = 7
  $shortcut.Description = 'DSH LAN Relay Hub（局域网消息总线）'
  $shortcut.Save()
  if (-not (Test-Path $startupShortcut)) { throw '快捷方式未创建成功' }
}

function Install-RunKey {
  if (-not (Test-Path $runKeyPath)) { New-Item -Path $runKeyPath -Force | Out-Null }
  New-ItemProperty -Path $runKeyPath -Name $runKeyName -Value (Get-LauncherCommand) -PropertyType String -Force | Out-Null
}

$installed = ''
$errors = @()
$order = switch ($Method) {
  'auto' { @('task', 'startup', 'runkey') }
  'task' { @('task') }
  'startup' { @('startup') }
  'runkey' { @('runkey') }
}

foreach ($candidate in $order) {
  try {
    switch ($candidate) {
      'task' { Install-Task; $installed = 'task' }
      'startup' { Install-StartupShortcut; $installed = 'startup' }
      'runkey' { Install-RunKey; $installed = 'runkey' }
    }
    if ($installed) { break }
  } catch {
    $errors += "$candidate：$($_.Exception.Message)"
  }
}

if (-not $installed) {
  Write-Host '所有自启方式都失败：' -ForegroundColor Red
  $errors | ForEach-Object { Write-Host "  - $_" -ForegroundColor Red }
  Write-Host ''
  Write-Host '可以手动把启动文件夹快捷方式指向：' -ForegroundColor Yellow
  Write-Host "  wscript.exe `"$launcherVbs`""
  exit 1
}

# 只保留一种方式，避免重复启动
if ($installed -ne 'task') {
  $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if ($task) {
    try { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue } catch { }
  }
}
if ($installed -ne 'runkey') {
  try {
    if (Get-ItemProperty -Path $runKeyPath -Name $runKeyName -ErrorAction SilentlyContinue) {
      Remove-ItemProperty -Path $runKeyPath -Name $runKeyName -Force
    }
  } catch { }
}
if ($installed -ne 'startup' -and (Test-Path $startupShortcut)) {
  Remove-Item $startupShortcut -Force
}

$methodLabel = switch ($installed) {
  'task' { "计划任务 $TaskName（登录时启动，支持异常重启）" }
  'startup' { "启动文件夹快捷方式 $startupShortcut" }
  'runkey' { "注册表自启项 HKCU\Software\Microsoft\Windows\CurrentVersion\Run\$runKeyName" }
}

Write-Host ''
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host '  LAN Relay Hub 开机自启已安装' -ForegroundColor Cyan
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host "  方式     : $methodLabel"
Write-Host "  启动器   : $launcherVbs"
Write-Host "  日志     : $logPath"
Write-Host "  配置文件 : $ConfigPath"
if ($errors.Count) {
  Write-Host "  回退记录 : $($errors -join ' / ')" -ForegroundColor DarkYellow
}
Write-Host ''

$existingListener = Get-NetTCPConnection -LocalPort 8787 -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
$launcherRunning = @(
  Get-CimInstance Win32_Process -Filter "Name='wscript.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like '*launch-hub.vbs*' }
).Count -gt 0

if (-not $NoStart) {
  if ($launcherRunning) {
    Write-Host "hub 已由启动器守护运行（PID $($existingListener.OwningProcess)），无需重复启动。" -ForegroundColor Green
  } else {
    if ($existingListener) {
      $proc = Get-CimInstance Win32_Process -Filter "ProcessId=$($existingListener.OwningProcess)" -ErrorAction SilentlyContinue
      if ($proc -and $proc.CommandLine -like '*hub.mjs*') {
        Write-Host "检测到未受启动器托管的 hub（PID $($existingListener.OwningProcess)），停止后交给自启动器守护…" -ForegroundColor Yellow
        Stop-Process -Id $existingListener.OwningProcess -Force -ErrorAction SilentlyContinue
        Start-Sleep -Milliseconds 800
      }
    }
    if ($installed -eq 'task') {
      Start-ScheduledTask -TaskName $TaskName
    } else {
      Start-Process -FilePath 'wscript.exe' -ArgumentList "`"$launcherVbs`"" -WindowStyle Hidden
    }
  }
  Start-Sleep -Seconds 2
}

$listen = Get-NetTCPConnection -LocalPort 8787 -State Listen -ErrorAction SilentlyContinue
Write-Host '当前状态：' -ForegroundColor Cyan
if ($listen) {
  Write-Host "  ✅ hub 正在监听 8787（PID $($listen[0].OwningProcess)）" -ForegroundColor Green
} else {
  Write-Host '  ⚠️ 8787 未监听，查看日志：' -ForegroundColor Yellow
  Write-Host "     Get-Content `"$logPath`" -Tail 30"
}
Write-Host ''
Write-Host '验证：' -ForegroundColor Cyan
Write-Host "  node `"$ProjectDir\relay-cli.mjs`" status"
Write-Host '取消自启：' -ForegroundColor Cyan
Write-Host "  powershell -NoProfile -ExecutionPolicy Bypass -File `"$ProjectDir\scripts\install-autostart.ps1`" -Remove"
Write-Host '说明：' -ForegroundColor DarkGray
Write-Host '  这是“登录时自启”。DSH 本身需要登录后使用，所以登录自启足够；' -ForegroundColor DarkGray
Write-Host '  计划任务方式失败通常是因为当前账户没有注册计划任务的权限，脚本会自动退回启动文件夹方式。' -ForegroundColor DarkGray
